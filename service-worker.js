const CACHE_PREFIX = 'invoice-app-';
const CACHE_VERSION = '56d37f671805a964'; // Generated by scripts/version-assets.cjs.
const CACHE_NAME = CACHE_PREFIX + encodeURIComponent(new URL(self.registration.scope).pathname) + '-' + CACHE_VERSION;
const SCOPE_CACHE_PREFIX = CACHE_PREFIX + encodeURIComponent(new URL(self.registration.scope).pathname) + '-';
const CACHE_ASSETS = [
    './', './index.html', './tong-hop.html', './main.js', './ui.js', './vietnam-time.js', './pwa.js',
    './src/output.css', './manifest.json', './images/favicon.ico',
    './images/icon-192x192.png', './images/icon-512x512.png'
];
const assetURLs = new Set(CACHE_ASSETS.map(path => new URL(path, self.registration.scope).href));

self.addEventListener('install', event => {
    event.waitUntil(caches.open(CACHE_NAME).then(cache => cache.addAll(
        CACHE_ASSETS.map(path => new Request(new URL(path, self.registration.scope), { cache: 'reload' }))
    )));
});

self.addEventListener('activate', event => {
    event.waitUntil(caches.keys().then(names => Promise.all(
        names.filter(name => name.startsWith(SCOPE_CACHE_PREFIX) && name !== CACHE_NAME)
            .map(name => caches.delete(name))
    )));
});

// Only this app's static assets participate. APIs and non-GET requests bypass the cache.
// A waiting worker activates after existing tabs close, avoiding a mid-session takeover.
self.addEventListener('fetch', event => {
    const assetURL = new URL(event.request.url);
    assetURL.search = '';
    if (event.request.method !== 'GET' || !assetURLs.has(assetURL.href)) return;
    event.respondWith((async () => {
        const cache = await caches.open(CACHE_NAME);
        let response;
        try { response = await fetch(event.request, { cache: 'no-cache' }); }
        catch { return (await cache.match(assetURL.href)) || Response.error(); }
        if (!response.ok) return (await cache.match(assetURL.href)) || response;
        try { await cache.put(assetURL.href, response.clone()); }
        catch { /* A full cache must not hide a successful network response. */ }
        return response;
    })());
});
